package migrations

import (
	"github.com/pocketbase/pocketbase/core"
	m "github.com/pocketbase/pocketbase/migrations"
)

func init() {
	m.Register(func(app core.App) error {
		collection := core.NewBaseCollection("Analysis")
		// Default nil API rules restrict access to superusers until backend
		// authentication and user ownership are implemented.
		collection.Fields.Add(
			&core.TextField{
				Name: "analysis_id", Required: true, Min: 36, Max: 36,
				Pattern: `^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$`,
				Help:    "UUID v4 generated by FastAPI, also returned in X-Analysis-ID.",
			},
			&core.SelectField{
				Name: "status", Required: true, MaxSelect: 1,
				Values: []string{"Processing", "Failed", "Complete"},
				Help:   "Failed if any category workflow fails; Complete only after all workflows succeed.",
			},
			&core.TextField{
				Name: "title", Max: 1000, Presentable: true,
				Help: "Generated title or fallback; empty until the title step completes.",
			},
			&core.JSONField{
				Name: "predictions", MaxSize: 2 << 20,
				Help: "Completed workflow results keyed by workflow ID, including category IDs, names and evidence quotes.",
			},
			&core.JSONField{
				Name: "error", MaxSize: 16 << 10,
				Help: "Failure details: workflow_id (nullable), code and message. Null on success.",
			},
			&core.AutodateField{Name: "created", OnCreate: true},
			&core.AutodateField{Name: "updated", OnCreate: true, OnUpdate: true},
		)
		collection.AddIndex("idx_analysis_uuid", true, "analysis_id", "")
		collection.AddIndex("idx_analysis_status_created", false, "status, created", "")
		return app.Save(collection)
	}, nil)
}
